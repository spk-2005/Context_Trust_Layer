def test_policy_agent_access_gate_enforcement():
    """AC-10: The Policy Answer Agent can access ONLY certified tiers."""
    gate = PolicyAgentAccessGate()

    # 1. Dual-Human Certified Claim -> FULL_ACCESS
    claim_dhc = {"candidate_id": "cand_001", "final_state": "DUAL_HUMAN_CERTIFIED"}
    allowed, level, reason = gate.check_access(claim_dhc, agent_id="agent_123")
    assert allowed is True
    assert level == AgentAccessLevel.FULL_ACCESS

    # 2. Auto-Approved Certified Claim -> RESTRICTED_ACCESS
    claim_aac = {"candidate_id": "cand_002", "final_state": "AUTO_APPROVED_CERTIFIED", "audit_certification": "PASSED"}
    allowed, level, reason = gate.check_access(claim_aac, agent_id="agent_123")
    assert allowed is True
    assert level == AgentAccessLevel.RESTRICTED_ACCESS

    # 3. Human Review Required Claim -> BLOCKED (NO_ACCESS)
    claim_hrr = {"candidate_id": "cand_003", "final_state": "HUMAN_REVIEW_REQUIRED"}
    allowed, level, reason = gate.check_access(claim_hrr, agent_id="agent_123")
    assert allowed is False
    assert level == AgentAccessLevel.NO_ACCESS
    assert "awaiting human review" in reason

    # 4. Quarantined / Rejected Claim -> BLOCKED (NO_ACCESS)
    claim_qr = {"candidate_id": "cand_004", "final_state": "QUARANTINED_REJECTED"}
    allowed, level, reason = gate.check_access(claim_qr, agent_id="agent_123")
    assert allowed is False
    assert level == AgentAccessLevel.NO_ACCESS
    assert "rejected" in reason

    # Filter claims list test
    mixed_claims = [claim_dhc, claim_aac, claim_hrr, claim_qr]
    filtered = gate.filter_claims_for_agent(mixed_claims, agent_id="agent_123")
    assert len(filtered) == 2
    assert set(c["candidate_id"] for c in filtered) == {"cand_001", "cand_002"}
