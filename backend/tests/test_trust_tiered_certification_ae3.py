def test_single_final_lifecycle_state_and_reconciliation(ae3_artifacts):
    """AC-8, AC-11: Every claim has exactly one final lifecycle state, totaling exactly 727 claims."""
    dhc = ae3_artifacts["dual_human_certified_claims.json"].get("claims", [])
    aac = ae3_artifacts["auto_approved_certified_claims.json"].get("claims", [])
    hrr = ae3_artifacts["human_review_required_claims.json"].get("claims", [])
    qr = ae3_artifacts["quarantined_rejected_claims.json"].get("claims", [])

    total_claims = len(dhc) + len(aac) + len(hrr) + len(qr)
    assert total_claims == 727, f"Total candidates ({total_claims}) must reconcile exactly to baseline 727"

    # Verify candidate ID disjointness (no candidate in more than 1 final state)
    id_sets = [
        set(c["candidate_id"] for c in dhc),
        set(c["candidate_id"] for c in aac),
        set(c["candidate_id"] for c in hrr),
        set(c["candidate_id"] for c in qr)
    ]
    all_ids = set()
    for s in id_sets:
        assert len(all_ids.intersection(s)) == 0, "Duplicate candidate ID found across final lifecycle states"
        all_ids.update(s)

    assert len(all_ids) == 727, "Must contain all 727 unique claims"

    # Reconciliation report checksum
    recon = ae3_artifacts["reconciliation_report.json"]["mathematical_reconciliation"]
    assert recon["checksum_verified"] is True
    assert recon["claims_lost_or_dropped"] == 0
    assert recon["duplicate_claims"] == 0


